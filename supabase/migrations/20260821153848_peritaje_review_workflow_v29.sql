create table if not exists public.lot_peritaje_reviews(
  id bigint generated by default as identity primary key,
  lot_id bigint not null unique references public.auction_lots(id) on delete cascade,
  external_lot_id text not null,
  source_attachment_url text,
  mechanical_risk text,
  transmission_risk text,
  body_risk text,
  safety_risk text,
  electrical_risk text,
  tires_risk text,
  documentation_risk text,
  missing_parts_risk text,
  overall_risk text,
  repair_low_cop numeric,
  repair_base_cop numeric,
  repair_high_cop numeric,
  notes text,
  reviewed_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint lot_peritaje_reviews_notes_len check(notes is null or char_length(notes)<=5000),
  constraint lot_peritaje_reviews_repair_nonnegative check(coalesce(repair_low_cop,0)>=0 and coalesce(repair_base_cop,0)>=0 and coalesce(repair_high_cop,0)>=0),
  constraint lot_peritaje_reviews_repair_order check(repair_low_cop is null or repair_base_cop is null or repair_high_cop is null or (repair_low_cop<=repair_base_cop and repair_base_cop<=repair_high_cop))
);

