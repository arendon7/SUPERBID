create or replace view public.dashboard_fasecolda_resolution_queue as
select
  d.external_lot_id,
  d.lot_id,
  d.title,
  d.brand,
  d.line,
  d.model_year,
  d.city,
  d.seller,
  d.current_bid_cop,
  d.closes_at,
  d.review_state,
  fm.status as automatic_status,
  fm.search_term,
  fm.best_code as automatic_best_code,
  fm.best_description as automatic_best_description,
  fm.best_score as automatic_best_score,
  fm.second_score as automatic_second_score,
  fm.candidate_count,
  case when mr.lot_id is null then 'UNRESOLVED' else 'RESOLVED' end as manual_resolution_status,
  mr.chosen_code,
  mr.chosen_description,
  mr.chosen_value_cop,
  mr.candidate_score as chosen_candidate_score,
  mr.candidate_rank as chosen_candidate_rank,
  mr.note as manual_note,
  mr.resolved_at,
  coalesce(ca.candidates,'[]'::jsonb) as candidates,
  'MANUAL_FASECOLDA_RESOLUTION_NOT_AUTOMATIC_MATCH'::text as interpretation
from public.dashboard_lot_current d
join public.lot_fasecolda_matches fm on fm.lot_id=d.lot_id
left join public.lot_fasecolda_manual_resolutions mr on mr.lot_id=d.lot_id
left join lateral (
  select jsonb_agg(
    jsonb_build_object(
      'rank',c.rank_no,
      'code',c.code,
      'description',c.description,
      'score',c.score,
      'current_value_cop',c.current_value_cop,
      'model_year',c.model_year,
      'evaluated_at',c.evaluated_at
    ) order by c.rank_no,c.code
  ) as candidates
  from public.lot_fasecolda_candidates c
  where c.lot_id=d.lot_id
) ca on true
where fm.status in ('AMBIGUOUS','MEDIUM') or mr.lot_id is not null;

revoke all on public.dashboard_fasecolda_resolution_queue from public,anon,authenticated;
grant select on public.dashboard_fasecolda_resolution_queue to service_role;

