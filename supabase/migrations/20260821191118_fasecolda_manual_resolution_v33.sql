  action text not null check (action in ('CONFIRM','CLEAR','INVALIDATE_IDENTITY_CHANGE')),
  previous_code text,
  previous_description text,
  previous_value_cop bigint,
  chosen_code text,
  chosen_description text,
  chosen_value_cop bigint,
  candidate_score numeric,
  candidate_rank integer,
  source_evaluated_at timestamptz,
  note text check (note is null or char_length(note) <= 2000),
  created_at timestamptz not null default clock_timestamp(),
  interpretation text not null default 'MANUAL_FASECOLDA_RESOLUTION_NOT_AUTOMATIC_MATCH',
  constraint lot_fasecolda_manual_resolution_history_interpretation_check
    check (interpretation='MANUAL_FASECOLDA_RESOLUTION_NOT_AUTOMATIC_MATCH')
