  on public.operational_alert_events(source_observed_at desc)
  where system_resolved_at is null;

create table if not exists public.operational_alert_action_history(
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.operational_alert_events(id) on delete cascade,
  external_lot_id text not null,
  action text not null check(action in ('ACKNOWLEDGE','DISMISS','REOPEN')),
  action_at timestamptz not null default clock_timestamp(),
  note text,
  previous_disposition text,
  new_disposition text,
  interpretation text not null default 'ALERT_LIFECYCLE_ACTION_NOT_BUY_SIGNAL'
    check(interpretation='ALERT_LIFECYCLE_ACTION_NOT_BUY_SIGNAL')
);

create index if not exists idx_operational_alert_action_history_alert
  on public.operational_alert_action_history(alert_id,action_at desc);

