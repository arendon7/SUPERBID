create table if not exists public.fasecolda_year_reference_case_dispositions(
  case_key text primary key,
  stored_brand text,
  term_brand text,
  line_term text,
  model_year integer,
  year_reference_reason text not null,
  available_years integer[],
  disposition_action text not null check(disposition_action in ('CONFIRM_COVERAGE_GAP','REQUEST_SOURCE_REFRESH','REFER_IDENTITY_REVIEW','REQUEST_MATCHER_RECHECK')),
  note text check(note is null or char_length(note)<=2000),
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  check(case_key ~ '^[0-9a-f]{32}$')
);

create table if not exists public.fasecolda_year_reference_case_disposition_history(
  id bigint generated by default as identity primary key,
  case_key text not null,
  action text not null check(action in ('CONFIRM_COVERAGE_GAP','REQUEST_SOURCE_REFRESH','REFER_IDENTITY_REVIEW','REQUEST_MATCHER_RECHECK','CLEAR')),
  year_reference_reason text,
  model_year integer,
  available_years integer[],
  note text check(note is null or char_length(note)<=2000),
  created_at timestamptz not null default clock_timestamp(),
  interpretation text not null default 'FASECOLDA_YEAR_GAP_DISPOSITION_NOT_VALUATION' check(interpretation='FASECOLDA_YEAR_GAP_DISPOSITION_NOT_VALUATION')
);

alter table public.fasecolda_year_reference_case_dispositions enable row level security;
alter table public.fasecolda_year_reference_case_disposition_history enable row level security;
